#!/usr/bin/env python3
"""
The transitional header on docs/header.html — generated from templates/, never written.

The header in production is the brand template, templates/arxiv_brand/header.html. The
examples in the page's "Transitional header" section are that template rendered by
templates/generate.py's own renderer (the one that writes the vendored adapter), so the
page shows exactly what production shows and cannot drift from it.

    python3.11 verification/gen-header-demos.py            # write docs/header.html
    python3.11 verification/gen-header-demos.py --check    # fail if the page is stale

templates/generate.py needs Python 3.10 or later. Only the text between the two marker
comments is generated; the rest of docs/header.html is written by hand.

The live examples change four things. So that several copies can share one page, each id
(and the for and aria-controls naming it) takes a suffix and each navigation gets its own
label. The logo comes from docs/assets/ rather than the asset route. The hidden IgnoreMe
link, a trap for crawlers that arxiv.org blocks, is left out, so a link checker run over
the docs never follows it. The Relevant code is the template's output unchanged.
"""

import html
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PAGE = REPO / "docs" / "header.html"
sys.path.insert(0, str(REPO / "templates"))
sys.path.insert(0, str(REPO))
import generate  # noqa: E402
from upload_static_assets import PUBLISHED  # noqa: E402

BEGIN = "<!-- BEGIN generated by verification/gen-header-demos.py: do not edit -->"
END = "<!-- END generated by verification/gen-header-demos.py -->"
SPAN = re.compile(re.escape(BEGIN) + r"\n(.*?)^([ \t]*)" + re.escape(END), re.S | re.M)
BAR = re.compile(r"<header\b.*", re.S)   # the bar and, after it, the hidden search overlay
INDENT = "      "


def icon(name: str) -> str:
    return (REPO / "docs" / "icons" / f"{name}.svg").read_text(encoding="utf-8").strip()


# What a page passes, in the order the examples show. The page actions example appears
# once the template has the header_page_actions variable.
STATES = [
    ("signed-out", "Signed out", {}, False),
    ("signed-in", "Signed in", {"signed_in": True}, False),
    ("phone", "Signed out, phone width", {}, True),
    ("page-actions", "With page actions", {"header_page_actions": (
        f'<a href="#">{icon("file-text")}<span class="is-sr-only">PDF</span></a>'
        f'<button type="button">{icon("list")}<span class="is-sr-only">Contents</span></button>')}, False),
]


def local(markup: str, base: str) -> str:
    """Asset-route URLs to the files in docs/ they are published from."""
    for source, published in PUBLISHED:
        if source.startswith("docs/"):
            markup = markup.replace(base + published, source[len("docs/"):])
    return markup


def example(markup: str, key: str, label: str) -> str:
    markup = re.sub(r'\s*<a [^>]*href="[^"]*/IgnoreMe"[^>]*></a>', "", markup)
    out = re.sub(r'\b(id|for|aria-controls)="([^"]+)"', lambda m: f'{m[1]}="{m[2]}-{key}"', markup)
    return out.replace('aria-label="Main navigation"', f'aria-label="Main navigation, {label.lower()} example"')


def indent(text: str, prefix: str) -> str:
    return "\n".join(prefix + line if line.strip() else "" for line in text.splitlines())


def generated() -> str:
    tokens, vars_ = generate.template("header")
    base = vars_["static_base"]["default"]
    parts = ['<div class="ds-card">']
    for key, label, context, narrow in STATES:
        if any(name not in vars_ for name in context):
            continue
        bar = BAR.search(generate.render(tokens, vars_, context).strip())[0]
        bar = re.sub(r"\n\s*\n", "\n", local(example(bar, key, label), base))
        bar = indent(bar, "  ")
        parts.append(f'  <p class="ds-panel-label">{label}</p>')
        parts.append(f'  <div class="demo-width-narrow">\n{indent(bar, "  ")}\n  </div>' if narrow else bar)
    code = html.escape(generate.render(tokens, vars_, {}).strip(), quote=False)
    code = re.sub(r"\n\s*\n", "\n", code)
    # The variables the examples set; the templates README describes every one.
    shown = [name for _, _, context, _ in STATES for name in context if name in vars_]
    terms = "\n".join(f"      <dt>{name}</dt>\n      <dd>{html.escape(vars_[name]['doc'], quote=False)}</dd>"
                      for name in shown)
    parts.append('  <details class="ds-acc"><summary>Relevant code</summary>\n'
                 '    <div class="ds-acc-body">\n'
                 f"<pre><code>{code}</code></pre>\n"
                 f"    <dl>\n{terms}\n    </dl>\n"
                 "    </div>\n"
                 "  </details>")
    parts.append("</div>")
    # The <pre> keeps its lines at the margin; everything else takes the section's indent.
    lines = "\n".join(parts).split("\n")
    out, in_pre = [], False
    for line in lines:
        in_pre = in_pre or line.startswith("<pre>")
        out.append(line if in_pre or not line.strip() else INDENT + line)
        in_pre = in_pre and "</code></pre>" not in line
    return "\n".join(out)


def render() -> str:
    text = PAGE.read_text(encoding="utf-8")
    m = SPAN.search(text)
    if not m:
        raise SystemExit(f"header.html has no generated span: add the two markers\n  {BEGIN}\n  {END}")
    return text[: m.start(1)] + generated() + "\n" + text[m.start(2):]


def main() -> int:
    out = render()
    if "--check" in sys.argv:
        if PAGE.read_text(encoding="utf-8") == out:
            print("PASS  header.html's transitional header matches templates/arxiv_brand/header.html")
            return 0
        print("FAIL  header.html's transitional header is stale — run: python3 verification/gen-header-demos.py")
        return 1
    PAGE.write_text(out, encoding="utf-8")
    print("header.html: transitional header written from templates/arxiv_brand/header.html")
    return 0


if __name__ == "__main__":
    sys.exit(main())
